#!/usr/bin/env python3
"""Writes the Windows app's string resources from strings.json (English, the source of truth).

English goes to App/Strings/en-US/Resources.resw. For each language the Mac app is translated
into, a string whose English text the Mac's string catalogs (*.xcstrings) also have gets the
Mac's translation, so the platforms read the same; the rest falls back to English at run time.
The Mac's %@ and %1$@ placeholders become .NET's {0}. Run it again when strings.json or the
Mac's catalogs change.
"""

import json
import pathlib
import re
import sys
from xml.sax.saxutils import escape

windows = pathlib.Path(__file__).resolve().parent.parent
repository = windows.parent
strings = json.loads((windows / 'Localization' / 'strings.json').read_text(encoding='utf-8'))

HEADER = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Windows/Localization/generate.py from strings.json{note}. Don't edit. -->
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
'''


def write_resw(language, entries, note=''):
    folder = windows / 'App' / 'Strings' / language
    folder.mkdir(parents=True, exist_ok=True)
    body = ''.join(f'  <data name="{escape(key, {chr(34): "&quot;"})}" xml:space="preserve"><value>{escape(value)}</value></data>\n'
                   for key, value in entries.items())
    (folder / 'Resources.resw').write_text(HEADER.format(note=note) + body + '</root>\n', encoding='utf-8')


def mac_placeholders_to_dotnet(text):
    """%@, %d, %1$@ … to {0} …, in order (positional ones by their position)."""
    counter = iter(range(100))
    def replace(match):
        position = match.group(1)
        return '{' + (str(int(position) - 1) if position else str(next(counter))) + '}'
    return re.sub(r'%(?:(\d+)\$)?(?:@|ld|lld|lu|d|i|f|s)', replace, text)


def dotnet_placeholders_to_generic(text):
    """{0}, {1:N0} … to a common form, to compare English texts across platforms."""
    return re.sub(r'\{\d+(?::[^}]*)?\}', '{}', text)


def mac_translations():
    """English text (placeholders made generic) to {language: translation}, from every catalog."""
    translations = {}
    for catalog in repository.rglob('*.xcstrings'):
        if '.build' in catalog.parts:
            continue
        data = json.loads(catalog.read_text(encoding='utf-8'))
        for key, entry in data.get('strings', {}).items():
            localizations = entry.get('localizations') or {}
            english = (localizations.get('en') or {}).get('stringUnit', {}).get('value', key)
            english = dotnet_placeholders_to_generic(mac_placeholders_to_dotnet(english))
            for language, localization in localizations.items():
                value = localization.get('stringUnit', {}).get('value')
                if language != 'en' and value and localization.get('stringUnit', {}).get('state') != 'needs_review':
                    translations.setdefault(english, {}).setdefault(language, mac_placeholders_to_dotnet(value))
    return translations


def write_english_fallback():
    """Loc.English.g.cs: the English strings, for when the resources can't be loaded."""
    lines = ['// Generated by Windows/Localization/generate.py from strings.json. Don\'t edit.', '',
             'namespace NetNewsWire.Windows;', '', 'internal static partial class Loc', '{',
             '    /// <summary>The English strings, for when the resources can\'t be loaded.</summary>',
             '    private static readonly Dictionary<string, string> English = new()', '    {']
    for key, value in strings.items():
        if '.' not in key:  # Keys with a property are XAML's (x:Uid).
            lines.append(f'        [{json.dumps(key, ensure_ascii=False)}] = {json.dumps(value, ensure_ascii=False)},')
    lines += ['    };', '}', '']
    (windows / 'App' / 'Loc.English.g.cs').write_text('\n'.join(lines), encoding='utf-8')


def main():
    write_resw('en-US', strings)
    write_english_fallback()
    translations = mac_translations()
    languages = sorted({language for by_language in translations.values() for language in by_language})
    for language in languages:
        translated = {}
        for key, english in strings.items():
            translation = translations.get(dotnet_placeholders_to_generic(english), {}).get(language)
            if translation and translation.count('{') == english.count('{'):
                translated[key] = translation
        write_resw(language, translated, f' and the Mac app\'s {language} translations')
        print(f'{language}: {len(translated)} of {len(strings)} strings from the Mac app; the rest fall back to English')


if __name__ == '__main__':
    sys.exit(main())
